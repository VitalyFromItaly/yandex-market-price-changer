/**
 * Разбор разметки сообщений Telegram. Чистый модуль: без Nest, без Node —
 * его импортирует и бэкенд, и админ-панель в браузере.
 *
 * Общий код, а не две копии, потому что расходятся такие пары молча: панель
 * начала бы показывать не то, что записано, и заметить это можно было бы
 * только сравнив глазами.
 *
 * Бот шлёт всё с `parse_mode: HTML`, поэтому в журнале лежит текст с тегами.
 * Хранится он как есть — иначе модалку «как в телеграме» построить не из чего,
 * а очистка при записи необратима.
 */

/**
 * Теги, которые Telegram действительно поддерживает в сообщениях.
 *
 * Всё остальное вырезается. Это второй рубеж, а не первый: данные
 * пользователя экранируются функцией esc() ещё при сборке сообщения, так что
 * в журнал разметка от продавца не попадает. Но панель отрисовывает HTML
 * через v-html, и полагаться на единственную проверку в другом слое здесь
 * нельзя — цена ошибки слишком велика.
 */
const ALLOWED_TAGS = ['b', 'strong', 'i', 'em', 'u', 's', 'strike', 'del', 'code', 'pre', 'br'];

/** Ссылки допускаются только на эти схемы: `javascript:` не должен пройти. */
const ALLOWED_LINK_SCHEMES = ['http://', 'https://', 'tg://'];

/**
 * Порядок значим: `&amp;` разворачивается последним, иначе `&amp;lt;`
 * превратится в `<` вместо `&lt;`.
 */
const ENTITIES: Array<[string, string]> = [
  ['&lt;', '<'],
  ['&gt;', '>'],
  ['&quot;', '"'],
  ['&#39;', "'"],
  ['&nbsp;', ' '],
  ['&amp;', '&'],
];

/** Разворачивает HTML-сущности в обычные символы. */
function decodeEntities(text: string): string {
  return ENTITIES.reduce((result, [entity, char]) => result.split(entity).join(char), text);
}

/**
 * Обезвреживает угловые скобки — и НАМЕРЕННО не трогает `&`.
 *
 * Строка из журнала уже является HTML: данные пользователя в ней экранированы
 * функцией esc() ещё при сборке сообщения. Экранировать `&` повторно значит
 * превратить `&quot;` в `&amp;quot;`, и вместо кавычки администратор увидит
 * буквальное «&quot;». Опасны здесь только `<` и `>`: без них не собрать тег.
 */
function neutralizeTags(text: string): string {
  return text.split('<').join('&lt;').split('>').join('&gt;');
}

/** Экранирование ЗНАЧЕНИЯ атрибута — тут кавычка и амперсанд как раз опасны. */
function escapeAttribute(value: string): string {
  return value.split('&').join('&amp;').split('"').join('&quot;').split('<').join('&lt;');
}

/**
 * Текст без разметки — то, что человек увидел на экране.
 *
 * Нужен для компактной строки таблицы: `🎫 <b>API-токен</b>` в ячейке
 * читается как мусор, потому что там разметка не отрисовывается.
 */
export function toPlainText(html: string): string {
  return decodeEntities(html.replace(/<[^>]*>/g, ''));
}

/**
 * Безопасный HTML для отрисовки в модалке — сообщение в том виде, в каком его
 * увидел пользователь в Telegram.
 *
 * Работает от обратного: сначала экранируется ВЕСЬ текст, затем возвращаются
 * только разрешённые теги. Так неизвестный тег не может уцелеть по недосмотру
 * — при обратном подходе (вырезать плохое) любая незамеченная конструкция
 * проходит насквозь.
 */
export function toSafeHtml(html: string): string {
  const escaped = neutralizeTags(html);

  // Парные и одиночные теги из белого списка: &lt;b&gt; → <b>.
  const tagPattern = new RegExp(`&lt;(/?)(${ALLOWED_TAGS.join('|')})\\s*/?&gt;`, 'gi');
  const withTags = escaped.replace(tagPattern, (_match, slash: string, tag: string) => {
    return `<${slash}${tag.toLowerCase()}>`;
  });

  // Ссылки — отдельно: у них есть атрибут, и его нужно проверить.
  // Кавычка в шаблоне обычная: `&` больше не экранируется, поэтому атрибут
  // выглядит здесь ровно так, как его написал бот.
  const linkPattern = /&lt;a\s+href=(?:"|')([^"']*)(?:"|')\s*&gt;/gi;
  let opened = 0;

  const withLinks = withTags.replace(linkPattern, (match, href: string) => {
    const url = decodeEntities(href);
    const allowed = ALLOWED_LINK_SCHEMES.some((scheme) => url.toLowerCase().startsWith(scheme));
    // Недопустимую схему не выбрасываем молча — показываем как текст, иначе
    // из журнала пропадёт факт, что в сообщении вообще была ссылка.
    if (!allowed) return match;
    opened += 1;
    return `<a href="${escapeAttribute(url)}" target="_blank" rel="noopener noreferrer">`;
  });

  // Закрывающий тег оживает только под открытый. Безусловная замена оставляла
  // болтающийся `</a>` там, где ссылку отвергли по схеме, — браузер такой тег
  // проглатывает, но в разметке это мусор ровно на пустом месте.
  return withLinks.replace(/&lt;\/a&gt;/gi, (match) => (opened-- > 0 ? '</a>' : match));
}
