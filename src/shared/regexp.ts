/**
 * Экранировать строку для `new RegExp`: пользовательский ввод в поиске не
 * должен становиться шаблоном — `.*` иначе нашёл бы всё, а `(` уронил бы запрос.
 * Модуль без импортов (паттерн `telegram-html.ts`).
 */
export function escapeRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
