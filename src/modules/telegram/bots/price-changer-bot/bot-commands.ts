/**
 * Что бот показывает в синей кнопке «Меню» — списком команд слева от поля ввода.
 *
 * Чистый модуль: ни telegraf, ни Nest, ни Mongo. Причина та же, по которой
 * появился `menu.constants.ts`: список обязан совпадать с реально
 * зарегистрированными командами, и проверяется это обычным юнит-тестом.
 *
 * Списков ДВА, и это не украшение. Раньше `setMyCommands` ставил полный список
 * глобально, то есть человек без доступа видел пять команд, каждая из которых
 * отвечала ему «Сначала нужно подать заявку на доступ». Интерфейс не должен
 * предлагать то, что заведомо не сработает, — тот же довод, по которому
 * существует `MENU_LAYOUT_UNCONFIGURED`.
 */

/** Одна команда в списке Telegram. Форма Bot API. */
export interface IBotCommand {
  command: string;
  description: string;
}

/** Кому какой список положен. Хранится в `UserAccess.commandScope`. */
export type TCommandScope = 'full' | 'guest';

/**
 * Список одобренного.
 *
 * Содержит ТОЛЬКО реально зарегистрированные команды. Убраны когда-то были
 * /price и /upload (изменение цен отключено, TASK-009), а также /files и
 * /cleanup — их обработчики удалили ещё при миграции, но команды продолжали
 * рекламироваться и молча не работали. Отчёты вызываются кнопками меню, а не
 * слэш-командами, поэтому их здесь нет.
 *
 * /users намеренно НЕ здесь: персональный список ставится по статусу доступа, а
 * не по правам администратора, и раздел администратора не должен светиться у
 * обычного продавца.
 */
export const FULL_COMMANDS: readonly IBotCommand[] = [
  { command: 'start', description: '🏠 Запустить бота' },
  { command: 'menu', description: '📋 Меню и отчёты' },
  { command: 'settings', description: '⚙️ Настройки' },
  { command: 'profile', description: '👤 Профиль' },
  { command: 'help', description: '❓ Помощь' },
];

/**
 * Список того, кому доступ ещё не выдан (или уже закрыт).
 *
 * Ровно `/start` — единственное, что гейт доступа пропускает при любом статусе
 * (`canPass` в `access.domain.ts`), и единственный способ для человека узнать,
 * что с его заявкой. Всё остальное упёрлось бы в отказ.
 */
export const GUEST_COMMANDS: readonly IBotCommand[] = [
  { command: 'start', description: '🏠 Запустить бота' },
];

/** Список по scope. Одна точка — чтобы ветка `if` не расползлась по вызовам. */
export function commandsFor(scope: TCommandScope): IBotCommand[] {
  return [...(scope === 'full' ? FULL_COMMANDS : GUEST_COMMANDS)];
}

/**
 * Какой список положен по статусу доступа.
 *
 * Отдельная функция, а не сравнение на месте: мест, где это решается, четыре
 * (гейт и три пути решения администратора), и разъехались бы они молча.
 */
export function scopeForStatus(status: string | undefined): TCommandScope {
  return status === 'approved' ? 'full' : 'guest';
}
