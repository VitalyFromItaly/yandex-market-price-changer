import { b, code } from '../../formatting/telegram-format';

import { MENU, SUPPORT_CONTACT } from './menu.constants';
import { stepHelp } from './onboarding';

/**
 * Справка — ОДИН текст на команду `/help` и на кнопку «Помощь».
 *
 * Отдельный файл появился потому, что оба входа расходились: у команды был свой
 * текст, а кнопка вообще вела в главное меню — заглушка из TASK-009, о которой
 * забыли. Пока текстов было два, они гарантированно отставали друг от друга.
 *
 * Ещё важнее содержание. Прежняя справка утверждала «работает только на чтение —
 * ничего не меняет в вашем магазине». После TASK-035 это неправда: бот
 * обновляет остатки из прайса. Обещание, которому код не соответствует, —
 * худший вид документации: пользователь принимает по нему решения.
 */
export function helpText(): string {
  return [
    `❓ ${b('Справка')}`,
    '',
    b('Отчёты по заказам'),
    `• ${MENU.SHIPPED_TODAY} — сколько уехало клиентам за сегодня и на какую сумму`,
    `• ${MENU.REDEEMED} — сколько выкуплено`,
    `• ${MENU.RETURNING} — что едет обратно: возвраты и невыкупы`,
    `• ${MENU.IN_TRANSIT} — всё в пути, файлом Excel`,
    '',
    `Суммы показываются двумя числами: за товары и с доставкой.`,
    '',
    b('Прибыль'),
    `${MENU.PROFIT} — чистая по выкупленным заказам за выбранный период.`,
    'Из суммы продажи вычитаются комиссия Маркета, налог и закуп.',
    'Закупочные цены бот берёт из того же прайса, которым вы обновляете остатки:',
    'закуп — это цена прайса минус скидка (по «Востоку» своя).',
    `Все четыре процента задаются в ${MENU.SETTINGS}.`,
    '',
    'Заказы с товарами, которых нет в прайсе, в расчёт не попадают —',
    'бот пишет, сколько их и на какую сумму.',
    '',
    b('Ежедневная рассылка'),
    `${MENU.SCHEDULE} — выберите отчёты и время, бот будет присылать их сам.`,
    'Время московское.',
    '',
    b('Обновление остатков'),
    'Пришлите файл прайс-листа — бот проставит остатки в Яндекс.Маркете.',
    `Чтобы сначала проверить без записи, добавьте к файлу подпись ${code('проверка')}:`,
    'бот сверит артикулы с каталогом и покажет, что нашлось, ничего не меняя.',
    '',
    'Позиции, которых нет в вашем каталоге, пропускаются — обычно это новинки,',
    'ещё не заведённые на Маркете.',
    '',
    b('Настройки'),
    `${MENU.SETTINGS} — подключение магазина. Нужен только API-токен,`,
    'больше ничего искать в кабинете не придётся.',
    '',
    // Инструкция берётся у визарда, а не переписывается сюда: это ровно тот же
    // текст, что показывает кнопка «❓ Как получить?». Скопировать его значило
    // бы завести вторую копию, которая отстанет от первой при первом же
    // изменении в кабинете Яндекса — ради чего и появился этот файл.
    stepHelp('token'),
    '',
    b('Команды'),
    `${code('/start')} — начать сначала`,
    `${code('/menu')} — главное меню`,
    `${code('/settings')} — настройки`,
    `${code('/profile')} — профиль`,
    `${code('/help')} — эта справка`,
    '',
    `💬 Поддержка: ${SUPPORT_CONTACT}`,
  ].join('\n');
}
