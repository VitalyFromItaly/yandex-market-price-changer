import type { IHelpModel } from './help.model';

import { renderHelp } from './help.model';
import { MENU, SUPPORT_CONTACT } from './menu.constants';
import { TOKEN_HELP_BLOCKS } from './onboarding';

/**
 * Справка — ОДИН текст на команду `/help` и на кнопку «Помощь».
 *
 * Отдельный файл появился потому, что оба входа расходились: у команды был свой
 * текст, а кнопка вообще вела в главное меню — заглушка из TASK-009, о которой
 * забыли. Пока текстов было два, они гарантированно отставали друг от друга.
 *
 * Ещё важнее содержание. Прежняя справка утверждала «работает только на чтение —
 * ничего не меняет в вашем магазине». После TASK-035 это неправда: бот
 * обновляет остатки из прайса. Обещание, которому код не соответствует, —
 * худший вид документации: пользователь принимает по нему решения.
 */
export function helpModel(): IHelpModel {
  return {
    title: 'Справка',
    sections: [
      {
        title: 'Отчёты по заказам',
        blocks: [
          {
            kind: 'list',
            items: [
              [`${MENU.SHIPPED_TODAY} — сколько уехало клиентам за сегодня и на какую сумму`],
              [`${MENU.REDEEMED} — сколько выкуплено`],
              [`${MENU.RETURNING} — что едет обратно: возвраты и невыкупы`],
              [`${MENU.IN_TRANSIT} — всё в пути, файлом Excel`],
            ],
          },
          { kind: 'text', spans: ['Суммы показываются двумя числами: за товары и с доставкой.'] },
        ],
      },
      {
        title: 'Прибыль',
        blocks: [
          {
            kind: 'text',
            spans: [
              [
                `${MENU.PROFIT} — две цифры за выбранный период: по заказам, оформленным`,
                'за период (их же вы видите в кабинете), и по уже выкупленным.',
                'Это разные заказы: сегодняшние выкупят позже, а сегодняшние выкупы',
                'оформлены раньше — складывать их нельзя.',
                'Из суммы продажи вычитаются комиссия Маркета, налог и закуп.',
                'Закупочные цены бот берёт из того же прайса, которым вы обновляете остатки:',
                'закуп — это цена прайса минус скидка (свою можно задать каждому бренду).',
                `Проценты задаются в ${MENU.SETTINGS}.`,
              ].join('\n'),
            ],
          },
          {
            kind: 'text',
            spans: [
              'Заказы с товарами, которых нет в прайсе, в расчёт не попадают —\n' +
                'бот пишет, сколько их и на какую сумму.',
            ],
          },
        ],
      },
      {
        title: 'Ежедневная рассылка',
        blocks: [
          {
            kind: 'text',
            spans: [
              `${MENU.SCHEDULE} — выберите отчёты и время, бот будет присылать их сам.\n` +
                'Время московское.',
            ],
          },
        ],
      },
      {
        title: 'Обновление остатков',
        blocks: [
          {
            kind: 'text',
            spans: [
              'Пришлите файл прайс-листа — бот проставит остатки в Яндекс.Маркете.\n' +
                'Чтобы сначала проверить без записи, добавьте к файлу подпись ',
              { code: 'проверка' },
              ':\nбот сверит артикулы с каталогом и покажет, что нашлось, ничего не меняя.',
            ],
          },
          {
            kind: 'text',
            spans: [
              'Позиции, которых нет в вашем каталоге, пропускаются — обычно это новинки,\n' +
                'ещё не заведённые на Маркете.',
            ],
          },
        ],
      },
      {
        title: 'Настройки',
        blocks: [
          {
            kind: 'text',
            spans: [
              `${MENU.SETTINGS} — подключение магазина. Нужен только API-токен,\n` +
                'больше ничего искать в кабинете не придётся.',
            ],
          },
          // Инструкция берётся у визарда, а не переписывается сюда: это ровно тот же
          // текст, что показывает кнопка «❓ Как получить?». Скопировать его значило
          // бы завести вторую копию, которая отстанет от первой при первом же
          // изменении в кабинете Яндекса — ради чего и появился этот файл.
          ...TOKEN_HELP_BLOCKS,
        ],
      },
      {
        title: 'Команды',
        blocks: [
          {
            kind: 'lines',
            items: [
              [{ code: '/start' }, ' — начать сначала'],
              [{ code: '/menu' }, ' — главное меню'],
              [{ code: '/settings' }, ' — настройки'],
              [{ code: '/profile' }, ' — профиль'],
              [{ code: '/help' }, ' — эта справка'],
            ],
          },
        ],
      },
    ],
    // Контакт отдаётся моделью, а не импортом константы: так SUPPORT_CONTACT
    // по-прежнему читает только этот файл (blocked-no-keyboard.test.ts), а CRM,
    // куда пускают лишь одобренных, получает его вместе со справкой.
    supportContact: SUPPORT_CONTACT,
  };
}

/** Справка для бота — HTML из той же модели, что получает CRM. */
export function helpText(): string {
  return renderHelp(helpModel());
}
