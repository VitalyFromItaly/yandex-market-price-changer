import { hoursUntilRetry } from '../shared/access.domain';

/**
 * Что бот пишет продавцу, когда доступ открыли или закрыли.
 *
 * Один модуль на все входы, а их теперь три: кнопки «Одобрить»/«Отклонить» в
 * карточке заявки, «⛔ Закрыть доступ» в разделе «👥 Пользователи» и тумблер
 * доступа в веб-панели. Ровно та причина, по которой в проекте появились
 * `help.text.ts` и `settings.text.ts`: два экрана с одним смыслом расходятся
 * молча, и продавец получает разные объяснения одного и того же события в
 * зависимости от того, каким путём администратор его выдал.
 *
 * Чистый модуль: ни telegraf, ни Mongo, ни Nest.
 */

export const ACCESS_GRANTED_TEXT = [
  '✅ <b>Доступ открыт!</b>',
  '',
  'Администратор одобрил вашу заявку. Выберите действие из меню ниже:',
].join('\n');

/**
 * Отказ по заявке. Часы до повторной попытки считаются от `rejectedAt`, а не
 * пишутся числом: срок один (`REJECTION_COOLDOWN_MS`), и второе место, где он
 * упоминается, разошлось бы с первым.
 */
export function accessRejectedText(rejectedAt: Date | undefined, now = new Date()): string {
  return [
    '⛔ <b>Заявка отклонена.</b>',
    '',
    `Введённые настройки удалены. Повторная регистрация будет доступна через ${hoursUntilRetry(
      rejectedAt,
      now,
    )} ч.`,
  ].join('\n');
}

/**
 * Отзыв уже выданного доступа — отдельный текст, а не отказ по заявке.
 *
 * У продавца, работавшего с ботом, никакой заявки на рассмотрении нет, и
 * «Заявка отклонена» он прочитал бы как ответ на что-то, чего не отправлял.
 * Молчать тоже нельзя: внезапно переставший отвечать бот выглядит поломкой, и
 * приходят разбираться именно как с поломкой.
 */
export const ACCESS_REVOKED_TEXT = '⛔ Доступ к боту закрыт администратором.';
