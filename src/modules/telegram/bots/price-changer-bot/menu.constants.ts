/**
 * Раскладка для того, кто ещё не заполнил креды.
 *
 * Показывать кнопки отчётов до настройки — значит вести пользователя в тупик:
 * нажатие упирается в «Сначала заполните настройки API». Интерфейс не должен
 * предлагать то, что заведомо не сработает.
 */
export const MENU_LAYOUT_UNCONFIGURED: readonly (readonly TMenuLabel[])[] = [
  [MENU.SETTINGS],
  [MENU.HELP],
];

/** Раскладка в виде обычного массива — телеграф ждёт мутабельный тип. */
export function menuLayout(): string[][] {
  return MENU_LAYOUT.map((row) => [...row]);
}

/** Сокращённая раскладка — пока креды не заполнены. */
export function unconfiguredMenuLayout(): string[][] {
  return MENU_LAYOUT_UNCONFIGURED.map((row) => [...row]);
}

/**
 * Та же раскладка плюс ряд администратора.
 *
 * Reply-клавиатура своя у каждого пользователя, поэтому кнопку достаточно не
 * добавлять — обычный пользователь её не увидит. Но на одном этом полагаться
 * нельзя: сам обработчик тоже проверяет права, иначе доступ зависел бы от
 * того, что нарисовано на экране.
 */
export function withAdminRow(layout: string[][]): string[][] {
  return [...layout, [MENU.USERS]];
}

/**
 * Посадить «🏪 Сменить магазин» в ряд к «Прибыли».
 *
 * Не отдельным рядом в конец: рядов семь, восьмой уходит за нижнюю границу
 * клавиатуры Telegram, и кнопку приходится искать прокруткой — то есть её как бы
 * и нет. «Прибыль» занимает свой ряд одна и стоит первой, так что соседнее место
 * свободно и видно сразу.
 *
 * Если «Прибыли» в раскладке нет (администратор закрыл `report_profit`, и
 * `featureMenuLayout` вырезал ряд), кнопка идёт ПЕРВЫМ рядом сама. Дописать её
 * в конец значило бы вернуть ту же проблему, только другому продавцу.
 *
 * Вход не мутируется — как в `menuLayout()` и `withAdminRow`.
 */
export function withSwitchStore(layout: string[][]): string[][] {
  const rows = layout.map((row) => [...row]);
  const profitRow = rows.find((row) => row.includes(MENU.PROFIT));

  if (profitRow) {
    profitRow.push(MENU.SWITCH_STORE);
    return rows;
  }

  return [[MENU.SWITCH_STORE], ...rows];
}
