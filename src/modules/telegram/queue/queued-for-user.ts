/**
 * «Уже собирается?» — общий предикат для экранов, уехавших в очередь.
 *
 * Защёлка живёт в ОЧЕРЕДИ, а не в памяти процесса: второй тап по кнопке иначе
 * ставит джобу, которая заведомо упрётся в лимит генерации отчёта (1/мин).
 * Списки короткие по построению (removeOnComplete), проверка дешёвая.
 *
 * Вынесено из FbyHandler, потому что таких экранов стало два, а фильтровать
 * надо и по имени джобы, и по продавцу — ровно тот класс кода, что расходится
 * в двух копиях. Проверка идёт по СВОЕМУ имени: отказать в обзоре складов из-за
 * того, что человек минуту назад нажал «📦 FBY», значило бы лечить лимит
 * запретом пользоваться ботом. Лимит лечится единственным циклом добычи отчёта
 * в FbyStockService, здесь — только защита от двойного нажатия.
 *
 * Модуль чистый: на вход обычные объекты, никакого Bull. Тип джобы объявлен
 * структурно по той же причине.
 */

/** То немногое, что нужно знать о джобе: как называется и чья она. */
export interface IQueuedJob {
  name?: string;
  data?: { telegramUserId?: string };
}

export function isQueuedFor(
  jobs: readonly (IQueuedJob | null)[],
  jobName: string,
  telegramUserId: string,
): boolean {
  return jobs.some(
    (job) => !!job && job.name === jobName && job.data?.telegramUserId === telegramUserId,
  );
}
