/**
 * Деньги финансового журнала — целые копейки.
 *
 * Отчёты Маркета отдают суммы float-ом в рублях, и сумма двадцати тысяч таких
 * чисел копит ошибку представления: 0.1 + 0.2 = 0.30000000000000004. В отчёте
 * о заказах это незаметно, а журнал сверяется с актом до копейки (TASK-108:
 * 469 903,39 ₽), и копейка расхождения там — уже «Есть расхождения». Поэтому
 * сумма переводится в целые копейки один раз, на входе, и дальше складываются
 * только целые — их сложение точное.
 *
 * `money.ts` остаётся в рублях: это арифметика отчётов о заказах, и переводить
 * её на копейки — отдельное решение, не эта задача.
 *
 * Лист без импортов.
 */

/**
 * Рубли → целые копейки. Число или строка («123,45», «−51 852,00»,
 * неразрывные пробелы). Нечисловое → `null`, а не 0: «суммы нет» и «сумма
 * ноль» — разные вещи, и спутать их значит тихо занизить статью (довод
 * `orderPurchase`).
 */
export function toKopecks(value: unknown): number | null {
  let rub: number;
  if (typeof value === 'number') {
    rub = value;
  } else if (typeof value === 'string') {
    const normalized = value
      .trim()
      // \s в JS покрывает и неразрывные пробелы (U+00A0, U+202F) — ими Excel делит разряды.
      .replace(/\s/g, '')
      .replace('\u2212', '-')
      .replace(',', '.');
    if (!/^-?\d+(\.\d+)?$/.test(normalized)) return null;
    rub = Number(normalized);
  } else {
    return null;
  }
  if (!Number.isFinite(rub)) return null;
  // Math.round снимает хвост представления: 0.30000000000000004 × 100 → 30.
  // `+ 0` превращает -0 в 0, чтобы сравнение с нулём не спотыкалось о знак.
  return Math.round(rub * 100) + 0;
}

/** Копейки → рубли, только для вывода. Складывать надо копейки, не результат. */
export function kopecksToRub(kopecks: number): number {
  return kopecks / 100;
}
