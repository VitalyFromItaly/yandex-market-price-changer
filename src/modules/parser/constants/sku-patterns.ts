export const SKU_PATTERNS = [
  // Паттерн 1: БРЕНД SKU (например: ORIENT FAA02003B, CASIO A1000D-7, ORIENT WV0091TY)
  /^(?:ORIENT|CASIO|SEIKO)\s+([A-Z0-9-]+)$/i,

  // Паттерн 2: Просто буквенно-цифровой код с дефисами (например: RA-AC0F06L10B, AW-500BB-4E)
  /^([A-Z]{2,3}-[A-Z0-9-]+)$/i,

  // Паттерн 3: Название с цифровым кодом и дополнительным текстом (например: Командирские 921892 с АПЗ)
  /^[А-Яа-я]+\s+(\d+[А-Яа-я\s]*(?:с\s+[А-Яа-я]+)?)$/,

  // Паттерн 4: Название с кодом и EXCLUSIVE (например: Амфибия 96077А EXCLUSIVE)
  /^[А-Яа-я]+\s+(\d+[А-Я]*(?:\s+EXCLUSIVE)?)$/,

  // Паттерн 5: Просто цифровой код с буквой (например: 58108А)
  /^(\d+[А-Я]*)$/,

  // Паттерн 6: SEIKO с кодом (например: Seiko SNP165P1, SEIKO SUR535P1, SEIKO SSK003K1)
  /^SEIKO\s+([A-Z0-9]+)$/i,

  // Паттерн 7: БРЕНД с кодом через точки (например: GOODYEAR G.S01213.01.04)
  /^(?:GOODYEAR|[A-Z]+)\s+([A-Z]+\.[A-Z0-9.]+)$/i,

  // Паттерн 8: ORIENT механические с кодом (например: ORIENT механические RA-AC0F06L10B)
  /^ORIENT\s+механические\s+([A-Z0-9-]+)$/i,

  // Паттерн 9: FABLER с дополнительным описанием (например: FABLER FL-500471-1 (сталь) кам. черный рем)
  /^FABLER\s+([A-Z0-9-]+)(?:\s+\([^)]+\))?(?:\s+.*)?$/i,

  // Паттерн 10: Множественные бренды G-SHOCK, BABY-G, PRO TREK (например: G-SHOCK, BABY-G, PRO TREK AWM-500GD-9A)
  /^(?:G-SHOCK,?\s*BABY-G,?\s*PRO TREK|EDIFICE,?\s*SHEEN)\s+([A-Z0-9-]+)$/i,

  // Паттерн 11: Русские названия с пробелами (например: Амфибия  71067А, Командирские 13031В)
  /^[А-Яа-я]+\s+(\d+[А-Я]*)$/,

  // Паттерн 12: CASIO с буквенно-цифровым кодом (например: CASIO LA-20WHS-2A)
  /^CASIO\s+([A-Z]{1,3}-[A-Z0-9-]+)$/i,
];
