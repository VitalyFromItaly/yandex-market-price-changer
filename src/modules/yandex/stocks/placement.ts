/**
 * ПРАВИЛО: на FBY остатки только читаются. Записывать их нельзя.
 *
 * Модель размещения кампании решает, кто распоряжается остатками:
 *
 *  - FBS / DBS / Express — товар лежит на складе ПРОДАВЦА. Он и сообщает Маркету
 *    количества, для этого и нужна загрузка прайса;
 *  - FBY — товар физически лежит на складе МАРКЕТА. Остаток там меняют приёмка
 *    поставки и продажи, а не продавец. Присланное им количество — это не факт
 *    о складе Маркета, а выдумка о чужом складе.
 *
 * Почему это стоит отдельного модуля, а не строчки в обработчике.
 *
 * 1. Без проверки запись уходит на СКЛАД МАРКЕТА. `getWarehouseId()` берёт
 *    первый склад из ответа кампании, не глядя, чей он. На живом кабинете
 *    (business 164225008) для FBY-кампании 148704883 он возвращает склад 147
 *    «Ростов-на-Дону-1» — тот самый, что лежит в `GET v2/warehouses`, списке
 *    фулфилмент-складов Маркета. Для FBS-кампаний 148655119 и 124425371 он
 *    возвращает 1826207 и 1519714, то есть настоящие склады магазина.
 * 2. Проверка в обработчике не защищает: путь записи может появиться новый
 *    (очередь, скрипт, админка), и про правило в нём забудут. Поэтому решение
 *    принимает `StockSyncService` — единственное место, которое пишет в Partner
 *    API, — а обработчик лишь избавляет продавца от бесполезного ожидания.
 * 3. Правило чистое: ни Nest, ни сети, ни телеграфа. Ошибка здесь не даёт ни
 *    ошибки компиляции, ни падения — она молча разрешает запись туда, куда
 *    нельзя. Ровно поэтому рядом лежат юнит-тесты.
 *
 * Читать остатки FBY можно и нужно: этим заняты экраны «🏬 Склады» и «📦 FBY».
 */

/** Модель размещения кампании, как её отдаёт `GET v2/campaigns`. */
export const PLACEMENT = {
  FBY: 'FBY',
  FBS: 'FBS',
  DBS: 'DBS',
  EXPRESS: 'EXPRESS',
} as const;

export type TPlacement = (typeof PLACEMENT)[keyof typeof PLACEMENT];

/**
 * Кто распоряжается остатками — по каждой известной модели.
 *
 * `Record<TPlacement, boolean>`, а НЕ массив разрешённых: массив типа
 * `TPlacement[]` не требует полноты союза, и новая модель размещения молча
 * оказалась бы не в нём. Здесь компилятор потребует явное решение для каждой —
 * а решение «можно ли писать остатки» как раз то, которое нельзя принять
 * умолчанием. Тот же приём, что у `FEATURE_KEY_SET` и `DRAFT_FIELDS`.
 */
const STOCK_WRITABLE: Record<TPlacement, boolean> = {
  [PLACEMENT.FBS]: true,
  [PLACEMENT.DBS]: true,
  [PLACEMENT.EXPRESS]: true,
  // Склад Маркета. Остатки только читаются — это и есть правило модуля.
  [PLACEMENT.FBY]: false,
};

/**
 * Может ли продавец записывать остатки этой модели.
 *
 * НЕИЗВЕСТНАЯ модель считается НЕзаписываемой, и это не перестраховка:
 * несправедливый отказ продавец чинит сменой магазина за два нажатия, а лишняя
 * запись на чужой склад не чинится ничем — Маркет не сообщает, что именно
 * применилось, и откатывать нечего.
 *
 * Сравнение регистронезависимое: `placementType` приходит из Маркета строкой и
 * в союз не типизирован, а «fbs» и «FBS» здесь обязаны значить одно.
 */
export function isStockWritable(placementType: string | undefined | null): boolean {
  if (!placementType) return false;
  return STOCK_WRITABLE[placementType.trim().toUpperCase() as TPlacement] === true;
}

/** Магазин в объёме, нужном для определения модели. Совпадает и с `IStoreRef`, и с `IStoreEntry`. */
export interface IPlacementRef {
  campaignId: string;
  placementType?: string;
}

/**
 * Модель подключённой кампании.
 *
 * Ищется по `campaignId`, а не берётся первой: токен открывает несколько
 * кампаний одного бизнеса, и у них РАЗНЫЕ модели — у живого продавца три FBS и
 * одна FBY под одним токеном. Взять первую значило бы решать судьбу записи
 * по чужому магазину.
 *
 * `undefined` — «не знаем», а не «нельзя»: у вызывающего может быть более
 * надёжный источник (живой ответ API против кэша в базе). Решение принимает он,
 * через `isStockWritable`, которая на `undefined` отвечает «нельзя».
 */
export function placementOfCampaign(
  stores: readonly IPlacementRef[] | undefined | null,
  campaignId: string | undefined | null,
): string | undefined {
  if (!stores?.length || !campaignId) return undefined;
  return stores.find((store) => store?.campaignId === campaignId)?.placementType;
}

