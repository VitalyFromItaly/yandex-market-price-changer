/**
 * Сопоставление наименования из прайса с артикулом в каталоге Яндекса.
 *
 * Правило подтверждено заказчиком и проверено против живого каталога магазина
 * «ALL BEST WATCH» (5599 артикулов, сверка 2026-07-29): артикул — это
 * наименование БЕЗ бренда в начале, хвост сохраняется ДОСЛОВНО.
 *
 * Хвост отбрасывать нельзя. Проверено по каталогу, там лежат ровно такие:
 *   «540533 EXCLUSIVE», «14038Г Космодайвер», «921306 с АПЗ», «350503 К-35»
 *
 * Отдельно про «К-35». Прежняя реализация (12 регулярок + запасной вариант
 * «взять последнее слово») давала на «Командирские 350501 К-35» артикул
 * «К-35» — одинаковый для ОДИННАДЦАТИ разных часов. Остатки писались бы в
 * одну карточку, последний затирал бы предыдущих, молча и без ошибки.
 * Правило «отрезать только бренд» устраняет это само: 4349 строк дают 4349
 * уникальных артикулов.
 */

/**
 * Бренды, которые отрезаются в начале наименования.
 *
 * ПОРЯДОК ЗНАЧИМ: двухсловные идут первыми. Иначе «Daniel Klein 11468-2»
 * совпал бы с более коротким префиксом и превратился в «Klein 11468-2».
 * По той же причине «ORIENT STAR» стоит перед «ORIENT».
 */
export const BRAND_PREFIXES = [
  'Daniel Klein',
  'ORIENT STAR',
  'ORIENT',
  'CASIO',
  'SEIKO',
  'Командирские',
  'Амфибия',
  'Восток',
  'Партнер',
] as const;

/** Приставка, с которой заведена часть каталога (285 позиций Daniel Klein). */
const CATALOG_TITLE_PREFIX = 'Наручные часы ';

/** Наименование без бренда. Если бренда нет — имя уже является артикулом. */
export function stripBrand(name: string): string {
  const trimmed = name.trim();

  for (const brand of BRAND_PREFIXES) {
    if (trimmed.toLowerCase().startsWith(`${brand.toLowerCase()} `)) {
      return trimmed.slice(brand.length).trim();
    }
  }

  return trimmed;
}

/**
 * Кандидаты в артикул, по убыванию вероятности.
 *
 * Каталог НЕОДНОРОДЕН — это выяснилось только при сверке с живыми данными:
 *   5312 артикулов — голый код          -> «540533 EXCLUSIVE»
 *    285 — с приставкой «Наручные часы» -> «Наручные часы Daniel Klein 14273-2»
 *      2 — с брендом                    -> «ORIENT RE-AT0205L00B Limited Edition»
 *
 * Одного правила поэтому недостаточно. Перебор поднял покрытие с 88.7 % до
 * 94.4 %: 246 позиций нашлись только по третьему варианту, одна — по второму.
 */
export function skuCandidates(name: string): string[] {
  const trimmed = name.trim();
  return [stripBrand(trimmed), trimmed, `${CATALOG_TITLE_PREFIX}${trimmed}`];
}

export interface IResolution {
  /** Артикул, найденный в каталоге, либо null. */
  sku: string | null;
  /** Какой из вариантов сработал — попадает в отчёт. */
  matchedBy: 'без бренда' | 'как в прайсе' | 'приставка «Наручные часы»' | null;
}

const MATCH_LABELS: IResolution['matchedBy'][] = [
  'без бренда',
  'как в прайсе',
  'приставка «Наручные часы»',
];

/**
 * Ищет наименование в каталоге. Не найдено — не ошибка: по решению заказчика
 * такие позиции ПРОПУСКАЮТСЯ. Это новинки, которых ещё нет на Маркете
 * (в сверке таких было 243 из 4349).
 */
export function resolveSku(name: string, catalog: ReadonlySet<string>): IResolution {
  const candidates = skuCandidates(name);

  for (let i = 0; i < candidates.length; i += 1) {
    if (catalog.has(candidates[i])) {
      return { sku: candidates[i], matchedBy: MATCH_LABELS[i] };
    }
  }

  return { sku: null, matchedBy: null };
}
