import { describe, it, expect } from 'vitest';

import { alphaBounds, refineCutout } from '../../src/modules/imaging/mask-refine';

/**
 * Доводка вырезанного объекта.
 *
 * Проверять это глазами на готовой карточке бесполезно: белая кайма шириной в
 * пиксель на превью не видна, а на тёмном фоне в полный размер выглядит как
 * светящийся контур. Поэтому — арифметика на отдельных пикселях.
 */
describe('Снятие каймы фона', () => {
  const rgba = (...bytes: number[]): Buffer => Buffer.from(bytes);

  it('не трогает цвет полностью непрозрачного пикселя', () => {
    const out = refineCutout(rgba(20, 30, 40, 255));

    expect([...out]).toEqual([20, 30, 40, 255]);
  });

  it('возвращает краевому пикселю его настоящий цвет, а не смесь с фоном', () => {
    // Чёрный корпус часов, наполовину перекрытый фоном: в кадре он выглядит
    // серым (128), и именно этот серый дал бы ореол на чёрной сцене.
    const out = refineCutout(rgba(128, 128, 128, 128));

    expect(out[0]).toBeLessThan(6);
    expect(out[1]).toBeLessThan(6);
    expect(out[2]).toBeLessThan(6);
  });

  it('обнуляет пиксель целиком, если покрытие ниже порога', () => {
    // Цвет тоже должен уйти в ноль: при масштабировании интерполяция подмешала
    // бы белый из «почти прозрачного» пикселя обратно в край объекта.
    const out = refineCutout(rgba(255, 255, 255, 5));

    expect([...out]).toEqual([0, 0, 0, 0]);
  });

  it('делает пиксель полностью непрозрачным, если покрытие выше порога', () => {
    const out = refineCutout(rgba(10, 10, 10, 250));

    expect(out[3]).toBe(255);
  });

  it('умеет работать с фоном, который не белый', () => {
    // Тот же серый пиксель, но фон объявлен чёрным — вычитать нечего, цвет
    // остаётся своим. Это страховка от «формула зашита под белый».
    const out = refineCutout(rgba(128, 128, 128, 255), { background: [0, 0, 0] });

    expect(out[0]).toBe(128);
  });

  it('отвергает буфер, который не RGBA', () => {
    expect(() => refineCutout(Buffer.alloc(5))).toThrow(/не кратна 4/);
  });

  it('отвергает перепутанные пороги', () => {
    expect(() => refineCutout(rgba(0, 0, 0, 255), { floor: 0.9, ceil: 0.1 })).toThrow(/floor/);
  });
});

describe('Габариты объекта', () => {
  /** Пустой кадр 4×4 с непрозрачными пикселями в указанных точках. */
  const frameWith = (points: Array<[number, number]>): Buffer => {
    const buffer = Buffer.alloc(4 * 4 * 4);
    for (const [x, y] of points) {
      buffer[(y * 4 + x) * 4 + 3] = 255;
    }
    return buffer;
  };

  it('считаются по непрозрачным пикселям, а не по размеру файла', () => {
    // У исходников от поставщика поля произвольные. Вписывать нужно сами часы,
    // иначе один и тот же масштаб даст на соседних карточках часы разного размера.
    expect(alphaBounds(frameWith([[1, 1], [2, 2]]), 4, 4)).toEqual({ left: 1, top: 1, width: 2, height: 2 });
  });

  it('включают крайние пиксели', () => {
    expect(alphaBounds(frameWith([[0, 0], [3, 3]]), 4, 4)).toEqual({ left: 0, top: 0, width: 4, height: 4 });
  });

  it('дают null, если вырезание оказалось пустым', () => {
    expect(alphaBounds(frameWith([]), 4, 4)).toBeNull();
  });
});
