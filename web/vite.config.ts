import { defineConfig } from 'vite';
import vue from '@vitejs/plugin-vue';

/**
 * Сборка админской панели журнала действий.
 *
 * Ключевое решение — сборка, а не Vue с CDN. Прод стоит на российском
 * хостинге, где внешние CDN недоступны ровно так же, как api.telegram.org
 * (см. TELEGRAM_UPDATE_MODE): панель, тянущая vue.global.js со стороннего
 * домена, открылась бы у разработчика и осталась бы белым экраном на проде.
 * Здесь весь код уходит в бандл, и страница не делает ни одного внешнего
 * запроса, кроме своего же /api/logs.
 *
 * Результат кладётся в web/dist и раздаётся самим Nest (см. main.ts), поэтому
 * деплой остаётся одним: тот же Dockerfile, тот же контейнер, тот же домен.
 */
export default defineConfig({
  root: __dirname,
  plugins: [vue()],
  build: {
    outDir: 'dist',
    emptyOutDir: true,
    // Без хеша путь предсказуем, но браузер закешировал бы старую панель.
    // Хеш в имени — единственное, что заставляет его забрать новую сборку.
    assetsDir: 'assets',
  },
  server: {
    port: 5173,
    // Панель импортирует чистый модуль разбора разметки из src/ бэкенда.
    // В сборке это работает само, а дев-серверу нужно явное разрешение
    // читать файлы выше своего root.
    fs: { allow: ['..'] },
    // Дев-сервер vite ходит за данными в локальный Nest: в разработке панель
    // и API живут на разных портах, в проде — на одном.
    proxy: {
      '/api': {
        target: 'http://localhost:3004',
        changeOrigin: true,
      },
    },
  },
});
